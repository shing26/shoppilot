-- round63 票 234 / U3：退款审批工单补偿（PostgreSQL 侧）
--
-- 与 H2 侧逐字同义；两侧版本钟由 PostgresMigrationParityTest 钉住。
create table refund_work_item_outbox (
    id bigint generated by default as identity,
    tenant_id varchar(32) not null,
    refund_id bigint not null,
    order_id varchar(32) not null,
    customer_id varchar(32) not null,
    status varchar(16) not null,
    attempts integer not null default 0,
    next_attempt_at timestamp(6) with time zone not null,
    last_error varchar(500),
    ticket_id varchar(40),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_refund_outbox_refund unique (refund_id)
);

create index idx_refund_outbox_due on refund_work_item_outbox (status, next_attempt_at);
