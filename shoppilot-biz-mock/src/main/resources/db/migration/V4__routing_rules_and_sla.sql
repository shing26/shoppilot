-- SLA 超时标记：只打戳，不改工单状态、不自动关单（ADR 0055 明确「不承诺解决时限」）。
alter table tickets add column escalated_at timestamp(6) with time zone;

-- 优先级口径换代：null 的旧含义是「不是情绪升级，按原口径排队」，等价于新枚举的 NORMAL。
-- 这是**语义等价回填**，不是改分母；存储字面量沿用既有契约（'high' 仍表示情绪升级，
-- verify-emotion.ps1 的活体判据逐字依赖它），枚举名 URGENT_EMOTION 是领域侧的叫法。
