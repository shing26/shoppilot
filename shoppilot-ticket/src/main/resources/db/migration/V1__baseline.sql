-- 队列列表按「队列 + 优先级 + 时间」取件，这是坐席台的主查询。
-- 与 round18 票 43 的教训一致：这条索引必须有上界（按队列取件天然有），
-- 当年那条无上界的工单列表查询正是「有索引反而更慢」的原因（docs/slow-query-optimization-2026-09-21.md）。
create index idx_ticket_queue_order on tickets (queue, priority, created_at);