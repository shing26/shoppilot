-- 工单与坐席服务的基线（round23 票 72 / ADR 0053、0055）
--
-- tickets 与 routing_rules 两张表从 biz-mock 搬到这里（所有者裁定 B：数据随服务走）。
-- 搬而不是共库的理由是物理的：H2 内存库在**进程内**，两个进程无法共享同一个库。
--
-- 表结构与 biz-mock 的 V3/V4 逐列一致（那段历史留在那边不动，那边的 V6 会把这两张表删掉），
-- 这里是从零重建，所以列定义写全。

create table tickets (
    created_at timestamp(6) with time zone not null,
    priority varchar(10),
    status varchar(20) not null,
    customer_id varchar(32) not null,
    tenant_id varchar(32) not null,
    id varchar(40) not null,
    reason varchar(40) not null,
    user_query varchar(512) not null,
    transcript clob not null,
    source varchar(24) not null,
    queue varchar(32),
    assignee varchar(32),
    sla_deadline timestamp(6) with time zone,
    escalated_at timestamp(6) with time zone,
    payload clob,
    primary key (id)
);

-- 规则表：分派规则是数据不是代码（ADR 0055）。通配用 '*' 表示。
create table routing_rules (
    id bigint generated by default as identity,
    tenant_id varchar(32) not null,
    source varchar(24) not null,
    reason varchar(40) not null,
    queue varchar(32) not null,
    priority varchar(10) not null,
    sla_minutes integer not null,
    enabled boolean not null,
    updated_at timestamp(6) with time zone not null,
    updated_by varchar(32),
    primary key (id)
);

-- 初始规则：与 biz-mock V4 播的六条逐字一致。搬迁不是改口径，所以两份种子必须相同；
-- 若将来两边规则表要各自演化，那是一件要重新裁决的事（现在它们是同一份规则的两次落地）。
