package com.shoppilot.tool.view;

/**
 * 退款审核态（ADR 0047 票 60）：买家读回时用来区分「受理」「放行」「驳回」三件事。
 *
 * <p>为什么需要独立的字段：订单状态 {@link OrderStatus#REFUNDING} 把"待审"与"已放行"
 * 混成同一个值，买家问"我那退款到哪了"时等于没答。此枚举只表达**审核走到了哪一步**，
 * 不表达到账 —— 到账的权威在支付通道，本仓没有，所以话术里明确把边界写下来而不是推进状态。
 */
public enum RefundReviewState {
    /** 已受理，等待人工审核；资金未动。 */
    PENDING_REVIEW,
    /** 人工已放行，资金进入处理；**到账由支付渠道处理**，不在客服承诺范围内。 */
    RELEASED,
    /** 人工已驳回，订单按时间戳推导回滚，买家可再申请。 */
    REJECTED
}
