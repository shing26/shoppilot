package com.shoppilot.tool.identity;

/**
 * 账号角色（round25 票 80 / ADR 0056、0058）。
 *
 * <p>放在契约库而不是某个服务里：令牌在网关签发与验签、角色判定在网关、账号存在业务侧，
 * 三处都要说同一个词。定义只写一份不是为了整齐，是为了让「角色拼错」这件事在编译期就发生。
 *
 * <p><b>这三个名字不是授权等级</b>：它们只回答「这个账号是谁」，不回答「这个动作允不允许」。
 * 动作级判定在网关侧按动作写死（工单动作与退款审核要求 AGENT 或 ADMIN，见 ADR 0058），
 * 不靠角色之间的比较——那种写法在加第四个角色时会静默失效。
 */
public enum UserRole {

    /** 买家：只能问、查自己的订单与自己被拦下的那条链路。 */
    BUYER,

    /** 坐席：领工单、处理、审核退款。 */
    AGENT,

    /** 管理员：坐席的动作，加上运维面。 */
    ADMIN
}